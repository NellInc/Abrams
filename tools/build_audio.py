#!/usr/bin/env python3
"""Create original, deterministic PCM effects; optional legacy scratch voices.

Default runs preserve existing speech. The explicit --scratch-voices path uses
eSpeak NG and cannot replace generative performances. Production crew speech is
generated by tools/generate_crew_voice.py. Original game audio is never read.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import shutil
import struct
import subprocess
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "godot/assets/audio"
RATE = 48000
SWITCH_MASTER = ROOT / "tools/audio/switch-approved-master.wav"
SWITCH_MASTER_SHA256 = "ba16a80749510afda5595766f7fccbe09290cc86abd1b822e3a92294b3244c8b"
LINES = {
    "ready": ("Commander", "Crew ready. Range is clear. Move out.", "en-us+m3"),
    "on_the_way": ("Gunner", "On the way!", "en-us+m2"),
    "loaded": ("Loader", "Up!", "en-us+m4"),
    "target": ("Gunner", "Target acquired.", "en-us+m2"),
    "hit": ("Commander", "Good hit.", "en-us+m3"),
    "cease_fire": ("Commander", "Cease fire. Range complete.", "en-us+m3"),
    "smoke": ("Gunner", "Smoke out.", "en-us+m2"),
    "empty": ("Loader", "No rounds remaining.", "en-us+m4"),
    "moving": ("Driver", "Moving.", "en-us+m5"),
}


def pcm(path: Path, samples: list[float], loop: bool = False) -> None:
    peak = max(max(abs(x) for x in samples), 1e-9)
    gain = min(0.89 / peak, 1.0)
    if not loop:
        for i in range(min(256, len(samples))):
            samples[i] *= i / 256
            samples[-1-i] *= i / 256
    values = (int(max(-1, min(1, x * gain)) * 32767) for x in samples)
    with wave.open(str(path), "wb") as stream:
        stream.setparams((1, 2, RATE, 0, "NONE", "not compressed"))
        stream.writeframes(struct.pack(f"<{len(samples)}h", *values))


def write_approved_switch(path: Path) -> dict:
    """Preserve the auditioned CC0/authored master without another PCM fade.

    Working if: rebuilding copies the approved bytes; a changed source fails
    before touching the destination. No external libraries or downloads.
    """
    raw = SWITCH_MASTER.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SWITCH_MASTER_SHA256:
        raise ValueError("Approved switch master hash mismatch")
    with wave.open(str(SWITCH_MASTER), "rb") as stream:
        if stream.getparams()[:4] != (1, 2, RATE, 5760):
            raise ValueError("Approved switch master format differs")
    path.write_bytes(raw)
    return {"sha256": SWITCH_MASTER_SHA256,
            "source": "Kenney CC0 interface contact with project-authored mechanical synthesis",
            "license": "CC0-1.0",
            "master": "tools/audio/switch-approved-master.wav",
            "provenance": "tools/audio/switch-approved-provenance.json"}


def effect(kind: str, seconds: float, seed: int) -> list[float]:
    rng = random.Random(seed)
    low = 0.0
    result = []
    for i in range(int(seconds * RATE)):
        t = i / RATE
        noise = rng.uniform(-1, 1)
        low += 0.035 * (noise - low)
        if kind == "cannon":
            x = 2.0 * low * math.exp(-t * 2.8)
            x += 0.65 * noise * math.exp(-t * 35)
            x += 0.5 * math.sin(2*math.pi*(62*t-9*t*t)) * math.exp(-t*5)
        elif kind == "impact":
            x = 2.5 * low * math.exp(-t * 2.2) + noise * 0.5 * math.exp(-t * 14)
            x += math.sin(t * 220) * math.exp(-t * 7) * 0.35
        elif kind == "machinegun":
            x = noise * math.exp(-t*48) * 0.65 + math.sin(t*720)*math.exp(-t*40)*0.3
        elif kind == "reload":
            x = 0.15 * noise * math.exp(-((t-0.23)/0.1)**2)
            for at in [0.02, 0.47, 0.62]:
                age = max(0.0,t-at)
                if t >= at:
                    x += (0.24*noise + 0.18*math.sin(age*1950)) * math.exp(-age*45)
        elif kind == "smoke":
            x = 0.45*noise*math.exp(-t*3) + 1.2*low*math.exp(-t*7)
        elif kind == "switch":
            x = (noise*0.22 + math.sin(t*14000)*0.17)*math.exp(-t*90)
        elif kind == "radio":
            # Authored attention signal, with no encoded tactical information.
            # The original radio dispatcher alone decides when it is requested.
            x=0.0
            for at,duration in [(0.02,0.055),(0.13,0.055),(0.24,0.055),(0.39,0.16)]:
                age=t-at
                if 0<=age<duration:
                    envelope=min(1.0,age/0.005,(duration-age)/0.008)
                    x+=0.3*envelope*math.sin(TAU*950*age)
        elif kind == "turret":
            # Periodic hydraulic motor/gear harmonics, separate from the turbine.
            # Integer frequencies and modulation keep the 2-second loop seamless.
            motor = (0.13*math.sin(TAU*230*t) + 0.055*math.sin(TAU*460*t)
                     + 0.025*math.sin(TAU*690*t) + 0.018*math.sin(TAU*1380*t))
            x = motor*(0.85+0.15*math.sin(TAU*3*t)) + 0.035*math.sin(TAU*58*t)
        else:
            # Periodic turbine spectrum. Every partial repeats at the loop boundary.
            x = 0.16*math.sin(TAU*48*t) + 0.10*math.sin(TAU*96*t)
            x += 0.08*math.sin(TAU*192*t) + 0.045*math.sin(TAU*768*t)
            x += 0.03*math.sin(TAU*1536*t)*(0.5+0.5*math.sin(TAU*4*t))
        result.append(math.tanh(x))
    return result


TAU = math.pi*2


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--effects-only", action="store_true", help="Default behavior: preserve voices")
    group.add_argument("--scratch-voices", action="store_true", help="Opt into legacy eSpeak development takes")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    receipt = OUT / "provenance.json"
    manifest = json.loads(receipt.read_text()) if receipt.exists() else {"effects": {}, "voices": {}}
    if args.scratch_voices and any(v.get("generator") != "eSpeak NG local" for v in manifest["voices"].values()):
        raise SystemExit("Existing generative speech is protected from scratch-voice replacement")
    manifest.pop("sample_rate", None)
    manifest["effects_sample_rate"] = RATE
    for i, (kind, duration) in enumerate({"cannon":2.4,"impact":2.8,"machinegun":0.22,"reload":0.85,"smoke":1.3,"switch":0.12,"engine":2.0,"turret":2.0,"radio":0.65}.items()):
        path = OUT / f"{kind}.wav"
        if kind == "switch":
            manifest["effects"][kind] = write_approved_switch(path)
            continue
        pcm(path, effect(kind, duration, 1988+i), loop=kind in ("engine", "turret"))
        manifest["effects"][kind] = {"sha256":hashlib.sha256(path.read_bytes()).hexdigest(), "source":"original mathematical synthesis, tools/build_audio.py"}
    if args.scratch_voices:
        manifest["voice_status"] = "development synthetic radio takes"
        # script_sha256 pins the generative crew script; these takes come from LINES
        # above (each records its own text), so a stale pin must not survive.
        manifest.pop("script_sha256", None)
        for cmd in ["espeak-ng", "ffmpeg"]:
            if not shutil.which(cmd):
                raise SystemExit(f"Missing {cmd}; effects created. Use --effects-only or install local voice tools.")
        with tempfile.TemporaryDirectory(prefix="abrams-voice-") as tmp:
            for cue, (role, line, voice) in LINES.items():
                dry = Path(tmp) / f"{cue}.wav"
                subprocess.run(["espeak-ng", "-v",voice,"-s","155","-p","36","-w",str(dry),line],check=True)
                path = OUT / f"voice_{cue}.wav"
                subprocess.run(["ffmpeg","-v","error","-y","-i",str(dry),"-af","highpass=f=320,lowpass=f=2900,acompressor=threshold=0.12:ratio=4,volume=1.4,alimiter=limit=0.89","-ar",str(RATE),"-ac","1",str(path)],check=True)
                manifest["voices"][cue] = {"role":role,"text":line,"generator":"eSpeak NG local","voice":voice,"sha256":hashlib.sha256(path.read_bytes()).hexdigest()}
    (OUT / "provenance.json").write_text(json.dumps(manifest, indent=2)+"\n")
    action = "generated" if args.scratch_voices else "preserved"
    print(f"Built {len(manifest['effects'])} effects; {action} {len(manifest['voices'])} voice takes")


if __name__ == "__main__":
    main()
